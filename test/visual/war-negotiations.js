import "../../src/style.css";
import { createGame } from "../../src/app/create-game";
import { createSeededWorld } from "../helpers/seeded-world";
import { createSimulationSettings } from "../../src/sim/simulation-settings";
import { getAdjacentNationPairs, getOwnerByMesoId } from "../../src/sim/world-cache";
import { declareWar } from "../../src/sim/war-state";
import { getWarNegotiation, proposePeaceTerms, whitePeaceTerms } from "../../src/sim/war-negotiations";
import { getDomesticUnrest } from "../../src/sim/domestic-unrest";
import { getDiplomacyState } from "../../src/sim/diplomacy";
import { warFatigueKey } from "../../src/sim/diplomatic-peace";
import { selectMapNation, getMapView } from "../../src/render/map-view-state";
const world = createSeededWorld({ seed: 101, width: window.innerWidth, height: window.innerHeight, quick: true });
world.settings = createSimulationSettings(); world.wars = [];
const [a, b] = getAdjacentNationPairs(world)[0];
const nation = world.nations.find((item) => item.id === a), enemy = world.nations.find((item) => item.id === b);
nation.character = { doctrine: "merchant", aggression: 0.25, cooperation: 0.9, innovation: 0.5, thrift: 0.8 };
enemy.character = { doctrine: "expansionist", aggression: 0.9, cooperation: 0.3, innovation: 0.5, thrift: 0.3 };
nation.resources.weapons = 80; enemy.resources.weapons = 200;
const war = declareWar(world.wars, b, a, 0); const negotiation = getWarNegotiation(world, war);
for (const unit of world.units) if (unit.nationId === a) unit.manpower *= 0.25;
nation.warCooperation = 0.05; enemy.warCooperation = 0.8;
world.time.fastTick = 3600; world.time.slowTick = 360; world.time.elapsedMs = 360000;
const unrest = getDomesticUnrest(world, a); unrest.pressure = 85; unrest.lowSupportSeconds = 250; unrest.phase = "crisis";
const owners = getOwnerByMesoId(world);
const target = world.mesoRegions.find((region) => region.type !== "sea" && owners.get(region.id) === a && region.id !== nation.capitalMesoId && region.neighbors.some((neighbor) => owners.get(neighbor.id) === b));
if (!target) throw new Error("Peace scene requires a contested border");
world.occupation.mesoById.set(target.id, b); world.occupation.version++;
getDiplomacyState(world).fatigueByWarId.set(warFatigueKey(war), 70);
proposePeaceTerms(world, b, a, { ...whitePeaceTerms(), demandedRegionIds: [target.id], demandedWeapons: 20, truceSeconds: 600 });
negotiation.automatic.set(a, false);
selectMapNation(world, a); getMapView(world).targetNationId = b;
createGame(document.getElementById("app"), { world, paused: true });
